import { copyFileSync, existsSync, readdirSync, statSync } from 'node:fs'
import { basename, join } from 'node:path'
import { URL } from 'node:url'
import type { OfflinePackResult, ToolManifest } from '@shared/types'
import { orderDownloadSources } from '@shared/manifest'
import { ensureDir, readJsonFile, writeJsonFile } from '../../utils/fs'
import { logger } from '../report/logger'
import { downloadFile } from '../downloader'
import { sha256File } from '../downloader/checksum'

/**
 * 离线包制作与导入（FR-12）。
 *
 * 关键设计：离线包里的文件**就按在线下载时的文件名**存放
 * （`<toolId>-<version>-<原文件名>`），导入时直接放进下载缓存目录。
 * 这样"离线安装"完全复用在线流程 —— 下载器发现目标文件已存在且 SHA-256 匹配
 * 就会跳过下载，不需要为离线模式维护第二条安装路径（少一条路径 = 少一类 bug）。
 */

export interface OfflineEntry {
  toolId: string
  version: string
  fileName: string
  sha256: string
  sizeBytes: number
  url: string
}

export interface OfflineIndex {
  schemaVersion: 1
  createdAt: string
  devkitVersion: string
  entries: OfflineEntry[]
}

/** 离线包内的归档目录名 */
export const OFFLINE_ARCHIVE_DIR = 'archives'
export const OFFLINE_INDEX_FILE = 'offline.json'

/**
 * 离线包里的文件名必须是"纯文件名"。
 *
 * path.join 会把 `..` 归一化掉，所以不校验就等于让一个手工构造的离线包
 * 读写下载目录之外的文件（安全审查 M3）。这里只接受单层文件名。
 */
const SAFE_FILE_NAME = /^[A-Za-z0-9][A-Za-z0-9._+-]{0,120}$/

export function assertSafeFileName(name: unknown, context: string): string {
  if (typeof name !== 'string' || !SAFE_FILE_NAME.test(name) || name.includes('..')) {
    throw new Error(`${context} 里的文件名不合法：${JSON.stringify(String(name).slice(0, 80))}`)
  }
  return name
}

/** 与 executor 保持一致的文件命名规则（改这里必须同步改 executor） */
export function archiveFileName(toolId: string, version: string, url: string): string {
  return `${toolId}-${version}-${basename(new URL(url).pathname)}`
}

export interface PackOfflineOptions {
  toolIds: string[]
  tools: Map<string, ToolManifest>
  packDir: string
  downloadDir: string
  devkitVersion: string
  mirrorPreference: Parameters<typeof orderDownloadSources>[1]
  proxy: string | null
  signal?: AbortSignal
  onProgress?: (done: number, total: number, label: string) => void
}

export async function packOffline(options: PackOfflineOptions): Promise<OfflinePackResult> {
  const { toolIds, tools, packDir, downloadDir, signal } = options

  try {
    ensureDir(packDir)
    const archivesDir = ensureDir(join(packDir, OFFLINE_ARCHIVE_DIR))

    const selected = toolIds
      .map((id) => tools.get(id))
      .filter((tool): tool is ToolManifest => Boolean(tool))

    const entries: OfflineEntry[] = []
    let totalBytes = 0
    let done = 0

    for (const tool of selected) {
      if (signal?.aborted) throw new Error('已取消')

      const version = tool.versions.find((item) => item.recommended) ?? tool.versions[0]
      if (!version?.source?.url || !version.source.sha256) {
        logger.warn('offline', `${tool.id} 没有可下载的版本，已跳过`)
        continue
      }

      const fileName = archiveFileName(tool.id, version.version, version.source.url)
      const target = join(downloadDir, fileName)

      const download = await downloadFile({
        sources: orderDownloadSources(version, options.mirrorPreference),
        sha256: version.source.sha256,
        sizeBytes: version.sizeBytes,
        targetFile: target,
        proxy: options.proxy,
        signal
      })

      if (!download.ok) {
        throw new Error(`${tool.id} 下载失败：${download.error}`)
      }

      const copyTarget = join(archivesDir, fileName)
      if (!existsSync(copyTarget)) copyFileSync(target, copyTarget)

      const size = statSync(copyTarget).size
      totalBytes += size
      done += 1
      options.onProgress?.(done, selected.length, tool.id)

      entries.push({
        toolId: tool.id,
        version: version.version,
        fileName,
        sha256: version.source.sha256,
        sizeBytes: size,
        url: version.source.url
      })
    }

    const index: OfflineIndex = {
      schemaVersion: 1,
      createdAt: new Date().toISOString(),
      devkitVersion: options.devkitVersion,
      entries
    }
    writeJsonFile(join(packDir, OFFLINE_INDEX_FILE), index)

    writeJsonFile(join(packDir, 'README.json'), {
      'zh-CN':
        '这是 devkit 生成的离线安装包。把整个文件夹拷到目标机器，在 devkit 里选择「从离线包安装」并指向本目录即可。',
      'en-US':
        'This is an offline pack generated by devkit. Copy the whole folder to the target machine and use "Install from offline pack" in devkit.'
    })

    logger.info('offline', `离线包已生成：${packDir}（${entries.length} 个文件 / ${totalBytes} 字节）`)
    return { ok: true, packDir, fileCount: entries.length, totalBytes, error: null }
  } catch (error) {
    const message = (error as Error).message
    logger.error('offline', `生成离线包失败：${message}`)
    return { ok: false, packDir: null, fileCount: 0, totalBytes: 0, error: message }
  }
}

export interface ImportResult {
  ok: boolean
  imported: number
  missing: string[]
  entries: OfflineEntry[]
  error: string | null
}

/**
 * 把离线包里的归档放进下载缓存，并逐个校验 SHA-256。
 * 校验失败的文件会被跳过（而不是写进去让后续安装以"校验失败"的名义报错），
 * 这样用户能立刻看到"这个离线包坏了"，而不是在安装中途才发现。
 */
export async function importOfflinePack(packDir: string, downloadDir: string): Promise<ImportResult> {
  try {
    const indexFile = join(packDir, OFFLINE_INDEX_FILE)
    if (!existsSync(indexFile)) {
      return { ok: false, imported: 0, missing: [], entries: [], error: `找不到 ${indexFile}` }
    }

    const index = readJsonFile<OfflineIndex>(indexFile)
    if (index.schemaVersion !== 1 || !Array.isArray(index.entries)) {
      return { ok: false, imported: 0, missing: [], entries: [], error: '离线包索引格式不匹配' }
    }

    ensureDir(downloadDir)
    const archivesDir = join(packDir, OFFLINE_ARCHIVE_DIR)
    const missing: string[] = []
    let imported = 0

    for (const entry of index.entries) {
      const fileName = assertSafeFileName(entry.fileName, '离线包索引')
      const source = join(archivesDir, fileName)
      if (!existsSync(source)) {
        missing.push(entry.fileName)
        continue
      }

      const actual = await sha256File(source)
      if (actual.toLowerCase() !== String(entry.sha256).toLowerCase()) {
        logger.warn('offline', `离线包内 ${fileName} 校验失败，已跳过`)
        missing.push(fileName)
        continue
      }

      copyFileSync(source, join(downloadDir, fileName))
      imported += 1
    }

    logger.info('offline', `离线包导入完成：${imported}/${index.entries.length} 个文件进入下载缓存`)
    return { ok: true, imported, missing, entries: index.entries, error: null }
  } catch (error) {
    const message = (error as Error).message
    logger.error('offline', `导入离线包失败：${message}`)
    return { ok: false, imported: 0, missing: [], entries: [], error: message }
  }
}

/** 列出磁盘上现有的离线包（设置页展示用） */
export function listOfflinePacks(dir: string): { name: string; entries: number }[] {
  if (!existsSync(dir)) return []
  const packs: { name: string; entries: number }[] = []
  for (const name of readdirSync(dir)) {
    const indexFile = join(dir, name, OFFLINE_INDEX_FILE)
    if (!existsSync(indexFile)) continue
    try {
      const index = readJsonFile<OfflineIndex>(indexFile)
      packs.push({ name, entries: index.entries?.length ?? 0 })
    } catch {
      // 索引坏了就不列出来
    }
  }
  return packs
}
